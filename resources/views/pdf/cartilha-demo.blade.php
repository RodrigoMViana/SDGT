<h1>Cartilha de preenchimento do Diagnóstico da Gestão Tributária Municipal</h1>
<p class="muted">Material de exemplo da base de demonstração.</p>
<h3>1. Quem preenche</h3>
<p>O servidor responsável pela gestão tributária (Secretário de Fazenda/Finanças ou equivalente) preenche o questionário. O gestor municipal (Prefeito ou autoridade designada) valida e assina.</p>
<h3>2. Como acessar</h3>
<p>Acesse com a conta GOV.BR ou com Certificado Digital ICP-Brasil. O CPF deve estar habilitado no Cadastro Único do Tribunal.</p>
<h3>3. Preenchimento</h3>
<p>Responda às perguntas de cada tema. As respostas podem ser salvas parcialmente. Perguntas condicionais ficam visíveis, mas só podem ser respondidas quando a condição for atendida.</p>
<h3>4. Evidências</h3>
<p>Anexe os documentos comprobatórios solicitados, preferencialmente em PDF textual (pesquisável).</p>
<h3>5. Prazos</h3>
<p>Prazo de preenchimento de 15 dias corridos, acrescido de 1 dia útil para validação e assinatura. Após o encerramento, o questionário fica disponível apenas para consulta.</p>
